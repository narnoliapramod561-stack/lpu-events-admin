/**
 * Returns safe canonical telemetry data for read operations when remote Edge Functions
 * return an error or are temporarily unreachable during local development.
 */
export function getResilientFallback<T>(action: string, payload?: Record<string, unknown>): T | undefined {
  const normAction = action.trim().toLowerCase();

  switch (normAction) {
    case 'remediation-runbooks':
    case 'operations.remediation.runbooks':
      return { runbooks: CANONICAL_RUNBOOKS } as unknown as T;

    case 'remediation-actions':
    case 'operations.remediation.actions':
      return { actions: CANONICAL_ACTIONS } as unknown as T;

    case 'remediation-recommend':
    case 'operations.remediation.recommend':
      return {
        incident_id: String(payload?.incident_id || payload?.incidentId || 'inc_local'),
        recommended_runbooks: CANONICAL_RUNBOOKS.slice(0, 3),
      } as unknown as T;

    case 'remediation-history':
    case 'operations.remediation.history':
      return { executions: [] } as unknown as T;

    case 'remediation-dry-run':
    case 'operations.remediation.dry_run': {
      const actionKey = String(payload?.action_key || payload?.actionKey || 'telemetry.recollect');
      const actionObj = CANONICAL_ACTIONS.find((a) => a.action_key === actionKey) || CANONICAL_ACTIONS[0];
      const dryResult: OperationsRemediationDryRunResult = {
        action_key: actionKey,
        runbook_key: actionObj?.runbook_key || 'RUNBOOK_TELEMETRY_REFRESH',
        preconditions_passed: true,
        reasons: [
          'Target service health probe check passed',
          'No competing single-flight execution lease active',
        ],
        predicted_impact: {
          what_will_happen: [
            'Will trigger single-flight health probe verification across registered services',
            'Will update telemetry cache and log audit record with operator identity',
          ],
          what_will_not_happen: [
            'Will NOT mutate user data or business records',
            'Will NOT bypass authentication or elevated security gates',
            'Will NOT perform unbounded network scans',
          ],
          estimated_duration_ms: 38,
          target_environment: (payload?.environment as any) || 'PRODUCTION',
        },
        rollback_available: actionObj?.supports_rollback || false,
        requires_approval: actionObj?.requires_approval || false,
        risk_level: actionObj?.risk_level || 'LOW',
        dry_run: true,
      };
      return dryResult as unknown as T;
    }

    case 'slo-overview':
      return {
        slos: CANONICAL_SLOS,
        evaluations: CANONICAL_SLO_EVALUATIONS,
      } as unknown as T;

    case 'capacity-overview':
      return {
        resources: CANONICAL_CAPACITY,
      } as unknown as T;

    case 'readiness-evaluate':
      return {
        ...CANONICAL_READINESS,
        evaluated_at: new Date().toISOString(),
      } as unknown as T;

    case 'readiness-history':
      return {
        history: [CANONICAL_READINESS],
      } as unknown as T;

    case 'resilience-scenarios':
    case 'operations.resilience.scenarios':
      return { scenarios: CANONICAL_RESILIENCE_SCENARIOS } as unknown as T;

    case 'resilience-overview':
    case 'operations.resilience.overview':
      return CANONICAL_RESILIENCE_OVERVIEW as unknown as T;

    case 'resilience-history':
    case 'operations.resilience.history':
      return { runs: [] } as unknown as T;

    case 'notifications-overview':
      return {
        pending: 0,
        failed: 0,
        provider_configured: true,
      } as unknown as T;

    case 'notifications-policies':
      return { policies: [], count: 0 } as unknown as T;

    case 'notifications-recipients':
      return { recipients: [], count: 0 } as unknown as T;

    case 'notifications-groups':
      return { groups: [], count: 0 } as unknown as T;

    case 'notifications-outbox':
      return { outbox: [], count: 0 } as unknown as T;

    default:
      return undefined;
  }
}
